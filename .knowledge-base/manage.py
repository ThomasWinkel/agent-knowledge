def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")
    parser = argparse.ArgumentParser(prog="manage.py", description="Knowledge base tooling.")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("index", help="regenerate index.md and the contents blocks of all topic indexes").set_defaults(func=cmd_index)
    sub.add_parser("lint", help="check structure, frontmatter, links, sizes, secrets and indexes").set_defaults(func=cmd_lint)

    p = sub.add_parser("new-topic", help="create a topic (or subtopic) folder with an index.md")
    p.add_argument("path", help="topic slug, e.g. billing-api, or billing-api/webhooks for a subtopic")
    p.add_argument("--title", required=True)
    p.add_argument("--description", required=True, help="one line: what the topic covers")
    p.set_defaults(func=cmd_new_topic)

    def add_setup_arguments(p: argparse.ArgumentParser) -> None:
        p.add_argument("--name", required=True)
        p.add_argument("--description", required=True, help="one sentence: purpose of the knowledge base")
        p.add_argument("--repository", help="git URL (default: from git remote origin)")
        p.add_argument("--contribution", choices=CONTRIBUTION_MODES,
                       help="how agents publish changes (default: with-project when embedded in a project, "
                            "pull-request on GitHub, otherwise direct-push)")
        p.add_argument("--trusted-author", action="append",
                       help="GitHub login for auto-merge in pull-request mode (repeatable; default: repo owner)")

    p = sub.add_parser("install", help="run from a template checkout: set up a knowledge base in --target "
                                       "(repository root, or a folder inside a project)")
    p.add_argument("--target", required=True, help="folder for the knowledge base, e.g. . or agent-knowledge")
    add_setup_arguments(p)
    p.add_argument("--force", action="store_true", help="overwrite existing files in the target")
    p.set_defaults(func=cmd_install)

    p = sub.add_parser("init", help="turn a copy of the template (e.g. from 'Use this template') into a knowledge base")
    add_setup_arguments(p)
    p.add_argument("--force", action="store_true", help="re-initialize an existing knowledge base")
    p.set_defaults(func=cmd_init)

    sub.add_parser("embed", help="embedded knowledge bases: create missing starter topics, print the pointer "
                                 "for the project's agent instructions (idempotent)").set_defaults(func=cmd_embed)

    p = sub.add_parser("pointer", help="print the entry that makes a project use this knowledge base "
                                       "(or some of its topics) permanently")
    p.add_argument("--topic", action="append", help="topic slug, e.g. billing-api (repeatable; default: whole knowledge base)")
    p.set_defaults(func=cmd_pointer)

    p = sub.add_parser("upgrade", help="run from a NEW template checkout: replace template-owned files in --target")
    p.add_argument("--target", required=True, help="path of the knowledge base to upgrade")
    p.add_argument("--force", action="store_true", help="copy files even if the version is not newer")
    p.set_defaults(func=cmd_upgrade)

    sub.add_parser("check-template", help="compare the template version with the latest version tag of the template").set_defaults(func=cmd_check_template)

    p = sub.add_parser("can-auto-merge", help="decide whether the current pull request may be merged automatically")
    p.add_argument("--author", required=True)
    p.add_argument("--base", required=True, help="base revision, e.g. origin/main")
    p.set_defaults(func=cmd_can_auto_merge)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
