# --- helpers -----------------------------------------------------------------


def rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def load_toml(path: Path) -> dict:
    with path.open("rb") as f:
        return tomllib.load(f)


def load_config() -> dict:
    path = ROOT / CONFIG_FILE
    if not path.is_file():
        fail(f"{CONFIG_FILE} not found in {ROOT}")
    return load_toml(path)


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def parse_version(version: str) -> tuple[int, ...]:
    if not VERSION_RE.match(str(version)):
        raise ValueError(f"invalid version {version!r}, expected MAJOR.MINOR.PATCH")
    return tuple(int(part) for part in version.split("."))


def github_slug(url: str) -> str | None:
    """Return 'owner/repo' for a GitHub HTTPS or SSH URL."""
    m = re.search(r"github\.com[:/]+([^/\s]+)/([^/\s]+?)(?:\.git)?/?$", url or "")
    return f"{m[1]}/{m[2]}" if m else None


def git(*args: str, cwd: Path = ROOT) -> str:
    # Never wait for credential prompts: agents and CI cannot answer them.
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0"}
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, encoding="utf-8", env=env)
    if result.returncode != 0:
        fail(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def git_toplevel(path: Path) -> Path | None:
    """Root of the git working tree containing `path` (which may not exist yet)."""
    probe = path.resolve()
    while not probe.exists():
        probe = probe.parent
    result = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=probe, capture_output=True, text=True)
    top = result.stdout.strip()
    return Path(top).resolve() if result.returncode == 0 and top else None


def is_embedded(root: Path) -> bool:
    """True if the knowledge base is a folder inside a larger repository, e.g. a project."""
    top = git_toplevel(root)
    return top is not None and top != root.resolve()


def set_github_output(**values: str) -> None:
    """Expose values as step outputs when running in GitHub Actions."""
    path = os.environ.get("GITHUB_OUTPUT")
    if path:
        with open(path, "a", encoding="utf-8") as f:
            for key, value in values.items():
                f.write(f"{key}={value}\n")


def yaml_value(value: str) -> str:
    if value.startswith(YAML_SPECIAL_START) or ": " in value or " #" in value or value.endswith(":"):
        return json.dumps(value, ensure_ascii=False)
    return value


def is_skipped(relpath: Path) -> bool:
    return any(part.startswith(".") or part in SKIP_DIRS for part in relpath.parts)


def guide_link(folder: Path) -> str:
    return Path(os.path.relpath(ROOT / GUIDE_FILE, folder)).as_posix()


# --- frontmatter -------------------------------------------------------------


def parse_frontmatter(text: str) -> tuple[dict[str, str] | None, list[str]]:
    """Parse the supported YAML subset: single-line `key: value` pairs. Returns (fields, problems)."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, ["missing frontmatter: file must start with '---'"]
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return None, ["frontmatter is not closed with '---'"]
    fields: dict[str, str] = {}
    problems: list[str] = []
    for line in lines[1:end]:
        if not line.strip():
            continue
        m = re.fullmatch(r"([A-Za-z_][\w-]*):(?:\s+(.*))?", line.rstrip())
        if not m:
            problems.append(f"unsupported frontmatter line {line.strip()!r}: use single-line 'key: value'")
            continue
        key, value = m[1], (m[2] or "").strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        elif yaml_value(value) != value:
            problems.append(f"frontmatter value of '{key}' contains YAML special characters and must be quoted")
        if key in fields:
            problems.append(f"duplicate frontmatter key '{key}'")
        fields[key] = value
    return fields, problems


def describe(path: Path) -> tuple[str, str]:
    fields, _ = parse_frontmatter(read_text(path))
    fields = fields or {}
    return fields.get("title") or path.stem, fields.get("description", "")


# --- index generation --------------------------------------------------------


def entry(title: str, link: str, description: str) -> str:
    return f"- [{title}]({link})" + (f" — {description}" if description else "")


def topic_indexes() -> list[Path]:
    topics = ROOT / TOPICS_DIR
    if not topics.is_dir():
        return []
    return sorted(p for p in topics.rglob(INDEX_FILE) if not is_skipped(p.relative_to(topics)))


def render_contents(index: Path) -> str:
    folder = index.parent
    lines = []
    for sub in sorted(p for p in folder.iterdir() if p.is_dir() and (p / INDEX_FILE).is_file()):
        lines.append(entry(*_titled(sub / INDEX_FILE, f"{sub.name}/{INDEX_FILE}")))
    for file in sorted(p for p in folder.glob("*.md") if p.name != INDEX_FILE):
        lines.append(entry(*_titled(file, file.name)))
    body = "\n".join(lines) if lines else "_No files yet._"
    return f"{BEGIN_MARKER}\n## Contents\n\n{body}\n{END_MARKER}"


def _titled(path: Path, link: str) -> tuple[str, str, str]:
    title, description = describe(path)
    return title, link, description


def with_contents(text: str, block: str) -> str:
    start, end = text.find(BEGIN_PREFIX), text.find(END_MARKER)
    if start == -1 or end < start:
        return text.rstrip("\n") + "\n\n" + block + "\n"
    return text[:start] + block + text[end + len(END_MARKER):]


def render_root_index(config: dict) -> str:
    topics = ROOT / TOPICS_DIR
    lines = []
    if topics.is_dir():
        for folder in sorted(p for p in topics.iterdir() if p.is_dir() and (p / INDEX_FILE).is_file()):
            lines.append(entry(*_titled(folder / INDEX_FILE, f"{TOPICS_DIR}/{folder.name}/{INDEX_FILE}")))
    body = "\n".join(lines) if lines else "_No topics yet._"
    parts = [ROOT_INDEX_NOTICE, f"# {config.get('name', 'Knowledge Base')}"]
    if config.get("description"):
        parts.append(config["description"])
    parts += [f"> **Agents:** read [{GUIDE_FILE}]({GUIDE_FILE}) first.", f"## Topics\n\n{body}"]
    return "\n\n".join(parts) + "\n"


def expected_indexes(config: dict) -> dict[Path, str]:
    expected = {ROOT / INDEX_FILE: render_root_index(config)}
    for index in topic_indexes():
        expected[index] = with_contents(read_text(index), render_contents(index))
    return expected


def write_indexes(config: dict) -> list[str]:
    changed = []
    for path, text in expected_indexes(config).items():
        if not path.is_file() or read_text(path) != text:
            write_text(path, text)
            changed.append(rel(path))
    return changed


def cmd_index(args: argparse.Namespace) -> int:
    changed = write_indexes(load_config())
    print("Updated: " + ", ".join(changed) if changed else "Indexes are up to date.")
    return 0


# --- lint --------------------------------------------------------------------


class Report:
    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def error(self, path: Path, message: str) -> None:
        self.errors.append(f"{rel(path)}: {message}")

    def warn(self, path: Path, message: str) -> None:
        self.warnings.append(f"{rel(path)}: {message}")


def lint_config(report: Report) -> dict | None:
    path = ROOT / CONFIG_FILE
    config = None
    try:
        config = load_toml(path)
    except (OSError, tomllib.TOMLDecodeError) as e:
        report.error(path, f"cannot read: {e}")
    if config is not None:
        required = ("name", "description") + (() if config.get("contribution") == "with-project" else ("repository",))
        for key in required:
            if not isinstance(config.get(key), str) or not config[key].strip():
                report.error(path, f"'{key}' must be a non-empty string")
        if config.get("contribution", DEFAULT_CONTRIBUTION) not in CONTRIBUTION_MODES:
            report.error(path, f"'contribution' must be one of: {', '.join(CONTRIBUTION_MODES)}")
        authors = config.get("auto_merge", {}).get("trusted_authors", [])
        if not isinstance(authors, list) or not all(isinstance(a, str) for a in authors):
            report.error(path, "'auto_merge.trusted_authors' must be a list of GitHub logins")

    path = ROOT / TEMPLATE_FILE
    try:
        meta = load_toml(path)
    except (OSError, tomllib.TOMLDecodeError) as e:
        report.error(path, f"cannot read: {e}")
    else:
        if not VERSION_RE.match(str(meta.get("version", ""))):
            report.error(path, "'version' must be MAJOR.MINOR.PATCH")
        if not isinstance(meta.get("repository"), str) or not meta["repository"].strip():
            report.error(path, "'repository' must be a git URL")
        if not isinstance(meta.get("owned"), list):
            report.error(path, "'owned' must be a list of paths")
        if not set(meta.get("standalone_only", [])) <= set(meta.get("owned", [])):
            report.error(path, "'standalone_only' must be a subset of 'owned'")
    return config


def lint_topics(report: Report) -> None:
    topics = ROOT / TOPICS_DIR
    if not topics.is_dir():
        return
    for path in sorted(topics.rglob("*")):
        relpath = path.relative_to(topics)
        if is_skipped(relpath):
            continue
        if path.is_dir():
            if not NAME_RE.match(path.name):
                report.error(path, "folder names must be lowercase kebab-case")
            if not (path / INDEX_FILE).is_file() and (len(relpath.parts) == 1 or any(path.glob("*.md"))):
                report.error(path, f"topic folder needs an {INDEX_FILE}")
            continue
        if len(relpath.parts) == 1:
            report.error(path, f"files belong into a topic folder: {TOPICS_DIR}/<topic>/")
        try:
            text = read_text(path)
        except UnicodeDecodeError:
            continue  # binary asset
        for name, pattern in SECRET_PATTERNS.items():
            if pattern.search(text):
                report.error(path, f"possible {name} found - never store secrets")
        if path.suffix == ".md":
            lint_markdown(report, path, text)


def lint_markdown(report: Report, path: Path, text: str) -> None:
    if not NAME_RE.match(path.stem):
        report.error(path, "file names must be lowercase kebab-case")
    fields, problems = parse_frontmatter(text)
    for problem in problems:
        report.error(path, problem)
    if fields is not None:
        for key in FRONTMATTER_KEYS:
            if not fields.get(key):
                report.error(path, f"frontmatter needs a non-empty '{key}'")
        for key in sorted(fields.keys() - set(FRONTMATTER_KEYS)):
            report.error(path, f"unknown frontmatter key '{key}' (allowed: {', '.join(FRONTMATTER_KEYS)})")
        if len(fields.get("description", "")) > DESCRIPTION_CHARS_WARN:
            report.warn(path, f"description longer than {DESCRIPTION_CHARS_WARN} characters")

    lines = text.count("\n") + 1
    if path.name == INDEX_FILE:
        start, end = text.find(BEGIN_PREFIX), text.find(END_MARKER)
        if start == -1 or end < start:
            report.error(path, f"generated contents block missing: run `{INDEX_COMMAND}`")
        else:
            lines -= text[start:end].count("\n") + 1
        if lines > INDEX_LINES_WARN:
            report.warn(path, f"{lines} hand-written lines; keep entry points under {INDEX_LINES_WARN}, move details into files")
        link = guide_link(path.parent)
        if f"]({link})" not in text:
            report.error(path, f"must link to the agent guide: > **Agents:** read [the knowledge base guide]({link}) first.")
    elif lines > FILE_LINES_MAX:
        report.error(path, f"{lines} lines (max {FILE_LINES_MAX}): split into smaller files or a subfolder")
    elif lines > FILE_LINES_WARN:
        report.warn(path, f"{lines} lines: consider splitting (error above {FILE_LINES_MAX})")
    if re.search(r"\bTODO\b", text):
        report.warn(path, "contains TODO")


def markdown_files() -> list[Path]:
    files = []
    for folder, dirs, names in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        files += [Path(folder) / n for n in names if n.endswith(".md")]
    return sorted(files)


def lint_links(report: Report, path: Path, boundary: Path) -> None:
    """Relative links must resolve inside `boundary`: the repository, including project files when embedded."""
    for target in LINK_RE.findall(STRIP_RE.sub("", read_text(path))):
        if not target or target.startswith("#") or re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", target):
            continue
        if target.startswith("/"):
            report.error(path, f"use relative links: {target}")
            continue
        resolved = (path.parent / urllib.parse.unquote(target.split("#")[0].split("?")[0])).resolve()
        if not resolved.is_relative_to(boundary):
            report.error(path, f"link points outside the repository: {target}")
        elif not resolved.exists():
            report.error(path, f"broken link: {target}")


def cmd_lint(args: argparse.Namespace) -> int:
    report = Report()
    config = lint_config(report)
    lint_topics(report)
    boundary = git_toplevel(ROOT) or ROOT
    for path in markdown_files():
        lint_links(report, path, boundary)
    guide = ROOT / GUIDE_FILE
    if guide.is_file() and f"pointer v{POINTER_VERSION}" not in read_text(guide):
        report.error(guide, f"must name the current pointer format 'agent-knowledge pointer v{POINTER_VERSION}'")
    if config is not None:
        for path, text in expected_indexes(config).items():
            if not path.is_file() or read_text(path) != text:
                report.error(path, f"index is out of date: run `{INDEX_COMMAND}`")
    for warning in report.warnings:
        print(f"warning: {warning}")
    for error in report.errors:
        print(f"error: {error}")
    print(f"{len(report.errors)} error(s), {len(report.warnings)} warning(s).")
    return 1 if report.errors else 0


